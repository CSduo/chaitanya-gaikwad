import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Re-spawn via tsx if needed
if (!process.env.XIYATO_TSX_RUNNER && !process.execArgv.some((a) => a.includes("tsx"))) {
  const npxCmd = process.platform === "win32" ? "npx.cmd" : "npx";
  const result = spawnSync(npxCmd, ["tsx", __filename, ...process.argv.slice(2)], {
    stdio: "inherit",
    env: { ...process.env, XIYATO_TSX_RUNNER: "1" },
    shell: true,
  });
  process.exit(result.status ?? 0);
}

const { default: sitemap } = await import("../app/sitemap");
const { discoverCanonicalUrls } = await import("../scripts/submit-indexnow");

console.log("=== SITEMAP INTEGRITY VERIFICATION ===");

// 1. Read prerender manifest
const manifest = JSON.parse(fs.readFileSync(".next/prerender-manifest.json", "utf8"));
const prerenderedPages = Object.keys(manifest.routes).filter(
  (r) => manifest.routes[r].routeType === "page" && !r.startsWith("/_")
);
console.log(`Prerendered page routes found in Next.js build: ${prerenderedPages.length}`);

// 2. Discover URLs from app/sitemap.ts
const entries = sitemap();
console.log(`Sitemap URLs generated by app/sitemap.ts: ${entries.length}`);

const CANONICAL_BASE = "https://xiyato.uk";
let hasErrors = false;
const sitemapPaths = [];

for (const entry of entries) {
  // Check 1: URL validity and canonical scheme + host
  let parsed;
  try {
    parsed = new URL(entry.url);
  } catch (e) {
    console.error(`✖ Malformed URL: ${entry.url}`);
    hasErrors = true;
    continue;
  }

  if (parsed.protocol !== "https:") {
    console.error(`✖ Non-HTTPS URL in sitemap: ${entry.url}`);
    hasErrors = true;
  }
  if (parsed.hostname !== "xiyato.uk") {
    console.error(`✖ Non-canonical host in sitemap: ${entry.url}`);
    hasErrors = true;
  }
  if (parsed.port) {
    console.error(`✖ Non-standard port in sitemap: ${entry.url}`);
    hasErrors = true;
  }
  if (entry.url.endsWith("/") && entry.url !== "https://xiyato.uk/") {
    console.error(`✖ Trailing slash in non-root URL: ${entry.url}`);
    hasErrors = true;
  }

  // Check 2: Genuine lastModified Date
  const lastMod = new Date(entry.lastModified);
  if (isNaN(lastMod.getTime())) {
    console.error(`✖ Invalid lastModified date in sitemap entry: ${entry.url}`);
    hasErrors = true;
  }

  const pathname = parsed.pathname;
  sitemapPaths.push(pathname);
}

// Check 3: Check bijection with prerendered page routes
const missingInPrerender = sitemapPaths.filter((p) => !prerenderedPages.includes(p));
const missingInSitemap = prerenderedPages.filter((p) => !sitemapPaths.includes(p));

if (missingInPrerender.length > 0) {
  console.error("✖ URLs in sitemap but NOT prerendered in build:", missingInPrerender);
  hasErrors = true;
} else {
  console.log("✔ All sitemap URLs correspond to real prerendered routes.");
}

if (missingInSitemap.length > 0) {
  console.warn("ℹ Prerendered pages not in sitemap:", missingInSitemap);
} else {
  console.log("✔ All prerendered page routes are covered in sitemap.");
}

// Check 4: discoverCanonicalUrls parity
const discovered = discoverCanonicalUrls();
if (discovered.length !== entries.length) {
  console.error(`✖ discoverCanonicalUrls mismatch: ${discovered.length} vs ${entries.length}`);
  hasErrors = true;
} else {
  console.log(`✔ discoverCanonicalUrls() returns exactly all ${entries.length} URLs.`);
}

// Check 5: Uniqueness
const uniqueUrls = new Set(entries.map((e) => e.url));
if (uniqueUrls.size !== entries.length) {
  console.error(`✖ Duplicate URLs found in sitemap: ${entries.length - uniqueUrls.size} duplicates`);
  hasErrors = true;
} else {
  console.log(`✔ All ${entries.length} URLs in sitemap are unique.`);
}

if (hasErrors) {
  console.error("\nRESULT: FAILED sitemap verification.");
  process.exit(1);
} else {
  console.log("\nRESULT: PASSED all sitemap verification checks!");
  process.exit(0);
}
